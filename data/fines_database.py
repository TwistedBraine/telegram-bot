class FinesDatabase:
    def __init__(self, db_name='fines.db'):
        os.makedirs('data', exist_ok=True)
        self.db_path = os.path.join('data', db_name)
        self.create_table()
    
    def create_table(self):
        conn = sqlite3.connect(self.db_path)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS daily_fines (
                date TEXT PRIMARY KEY,
                category TEXT,
                article TEXT,
                description TEXT,
                fine TEXT,
                message_id INTEGER,
                chat_id INTEGER
            )
        """)
        conn.commit()
        conn.close()
    
    def get_today_fine(self):
        """Получить штраф на сегодня"""
        today = datetime.now().strftime("%Y-%m-%d")
        conn = sqlite3.connect(self.db_path)
        cursor = conn.cursor()
        
        cursor.execute("SELECT * FROM daily_fines WHERE date = ?", (today,))
        result = cursor.fetchone()
        conn.close()
        
        return result
    
    def save_today_fine(self, category, article, description, fine, message_id, chat_id):
        """Сохранить сегодняшний штраф"""
        today = datetime.now().strftime("%Y-%m-%d")
        conn = sqlite3.connect(self.db_path)
        
        conn.execute("""
            INSERT OR REPLACE INTO daily_fines 
            (date, category, article, description, fine, message_id, chat_id) 
            VALUES (?, ?, ?, ?, ?, ?, ?)
        """, (today, category, article, description, fine, message_id, chat_id))
        
        conn.commit()
        conn.close()
    
    def get_yesterday_message_id(self):
        """Получить ID вчерашнего сообщения для удаления"""
        yesterday = (datetime.now() - timedelta(days=1)).strftime("%Y-%m-%d")
        conn = sqlite3.connect(self.db_path)
        cursor = conn.cursor()
        
        cursor.execute("SELECT message_id, chat_id FROM daily_fines WHERE date = ?", (yesterday,))
        result = cursor.fetchone()
        conn.close()
        
        return result

    def get_random_fine(self):
        """Получить случайный штраф из базы"""
        all_fines = []
        for category, fines in FINES_DATA.items():
            for fine in fines:
                all_fines.append({
                    'category': category,
                    'article': fine['article'],
                    'description': fine['description'],
                    'fine': fine['fine'],
                    'advice': fine['advice']
                })
        
        return random.choice(all_fines) if all_fines else None

